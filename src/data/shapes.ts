/**
 * Placeholder cut-outs, drawn in a 200×200 box.
 * Used whenever a work has no photo yet: the piece is shown as an appliquéd
 * silhouette in its own pattern, with a stitched outline. Replace with photos
 * by dropping files into /public/images/works (see README).
 *
 * Fill keys:  p = the work's own pattern   r = red   k = ink   w = paper
 *             d = red dots  i = paper dots on ink   s = red stripes   e = lash eyes
 */
export type Fill = 'p' | 'r' | 'k' | 'w' | 'd' | 'i' | 's' | 'e';
export type Part = [d: string, fill: Fill];

const scallopRow = (x0: number, x1: number, y: number, n: number, depth = 9) => {
  const w = (x1 - x0) / n;
  let d = '';
  for (let i = 0; i < n; i++) d += ` A${(w / 2).toFixed(1)},${depth} 0 0 1 ${(x1 - w * (i + 1)).toFixed(1)},${y}`;
  return d;
};

/** one flounce tier: a trapezoid with a scalloped hem */
const tier = (yTop: number, yBot: number, wTop: number, wBot: number, cx = 100, n = 6): string =>
  `M${cx - wTop / 2},${yTop} L${cx + wTop / 2},${yTop} L${cx + wBot / 2},${yBot}` +
  scallopRow(cx - wBot / 2, cx + wBot / 2, yBot, n).replace(/ A/g, ' A') + ' Z';

const tierRev = (yTop: number, yBot: number, wTop: number, wBot: number, cx = 100, n = 6) => {
  // hem drawn right→left so scallops bulge downward
  const x0 = cx - wBot / 2, x1 = cx + wBot / 2, w = (x1 - x0) / n;
  let d = `M${cx - wTop / 2},${yTop} L${cx + wTop / 2},${yTop} L${x1},${yBot}`;
  for (let i = 0; i < n; i++) d += ` A${(w / 2).toFixed(1)},8 0 0 1 ${(x1 - w * (i + 1)).toFixed(1)},${yBot}`;
  return d + ' Z';
};

